const TEEN_CHEAT_ORDER = {
  bored: ["seeking", "neutral", "sensitive"],
  frustrated: ["sensitive", "seeking", "neutral"],
  overload: ["sensitive", "neutral", "seeking"],
};

function getTeenCheatSheet(scores, language = "en") {
  const pack = TEEN_CHEAT_SHEET[language] || TEEN_CHEAT_SHEET.en;
  const fallback = TEEN_CHEAT_SHEET.en;
  const list = Array.isArray(scores) ? scores : [];

  const buildState = (stateKey) => {
    const order = TEEN_CHEAT_ORDER[stateKey] || ["sensitive", "seeking", "neutral"];
    return list
      .slice()
      .sort((a, b) => {
        const rankA = order.indexOf(a?.profile);
        const rankB = order.indexOf(b?.profile);
        const rankDiff = (rankA === -1 ? order.length : rankA) - (rankB === -1 ? order.length : rankB);
        if (rankDiff !== 0) return rankDiff;
        return domainRoadmapStrength(b || {}) - domainRoadmapStrength(a || {});
      })
      .slice(0, 3)
      .map((score) => ({
        id: score.id,
        icon: score.icon,
        title: score.shortTitle || score.title,
        profile: score.profile,
        text: pack[stateKey]?.[score.id] || fallback[stateKey]?.[score.id] || "",
      }))
      .filter((item) => item.text);
  };

  return {
    bored: buildState("bored"),
    frustrated: buildState("frustrated"),
    overload: buildState("overload"),
  };
}

/**
 * Shared classification rule: tally answers into sensitive / avoiding,
 * sensory neutral, and sensory seeking, then pick whichever count is highest.
 * Used for both a single sense and the overall (all senses combined) score.
 *
 * Ties: if sensitive and seeking tie for highest, treat as neutral (mixed).
 * If a pole ties with neutral for highest, prefer neutral.
 */
function classifyBalance(sensitive, seeking, scored, neutral = 0) {
  if (!scored) return { profile: "neutral", threshold: 0, diff: 0 };

  const counts = {
    sensitive: sensitive || 0,
    neutral: neutral || 0,
    seeking: seeking || 0,
  };
  const diff = counts.sensitive - counts.seeking;
  const max = Math.max(counts.sensitive, counts.neutral, counts.seeking);
  const tied = ["sensitive", "neutral", "seeking"].filter((key) => counts[key] === max);

  // Unique highest wins; any tie falls back to neutral (mixed / unclear lean).
  const profile = tied.length === 1 ? tied[0] : "neutral";

  return { profile, threshold: max, diff };
}

/**
 * Position for the sensitive-neutral-seeking bar from the three tallies:
 * sensitive at 0, neutral at 50, seeking at 100 (weighted average).
 */
function balancePercent(sensitive, seeking, scored, threshold, neutral = 0) {
  const total = (sensitive || 0) + (seeking || 0) + (neutral || 0);
  if (!total) return 50;

  return Math.round(((neutral || 0) * 50 + (seeking || 0) * 100) / total);
}

function scoreDomain(questions, answers) {
  let sensitive = 0;
  let seeking = 0;
  let neutral = 0;
  let scored = 0;

  questions.forEach((q, i) => {
    const answer = answers[i];
    if (answer === undefined || answer === null) return;

    // Every answered item counts toward the total — including neutral-type
    // questions and "no" answers, which sit in the middle ground.
    scored += 1;
    const yes = answer === true;

    if (q.type === "sensitive" && yes) {
      sensitive += 1;
    } else if (q.type === "seeking" && yes) {
      seeking += 1;
    } else {
      neutral += 1;
    }
  });

  if (scored === 0) {
    return { sensitive: 0, seeking: 0, neutral: 0, profile: "neutral", scored: 0 };
  }

  const { profile } = classifyBalance(sensitive, seeking, scored, neutral);

  return { sensitive, seeking, neutral, profile, scored };
}

function scoreAllDomains(domainAnswers, domains, language = "en", respondent = "adult") {
  const profileLabels = getProfileLabels(language, respondent);
  return domains.map((domain) => {
    const answers = domainAnswers[domain.id] || [];
    const result = scoreDomain(domain.questions, answers);
    return {
      id: domain.id,
      title: domain.title,
      shortTitle: domain.shortTitle || domain.title,
      blurb: domain.blurb || "",
      icon: domain.icon,
      ...result,
      meta: profileLabels[result.profile],
    };
  });
}

/**
 * Adds every sensory system together into one overall score, then classifies
 * the person as a whole using the same highest-of-three rule applied to each sense.
 */
function scoreOverall(domainScores, language = "en", respondent = "adult") {
  const profileLabels = getProfileLabels(language, respondent);

  const totals = (domainScores || []).reduce(
    (acc, score) => {
      acc.sensitive += score.sensitive || 0;
      acc.seeking += score.seeking || 0;
      acc.neutral += score.neutral || 0;
      acc.scored += score.scored || 0;
      if (score.profile) acc.systems[score.profile] += 1;
      return acc;
    },
    {
      sensitive: 0,
      seeking: 0,
      neutral: 0,
      scored: 0,
      systems: { sensitive: 0, neutral: 0, seeking: 0 },
    }
  );

  const { profile, threshold, diff } = classifyBalance(
    totals.sensitive,
    totals.seeking,
    totals.scored,
    totals.neutral
  );
  const signals = totals.sensitive + totals.seeking;

  return {
    ...totals,
    signals,
    profile,
    threshold,
    diff,
    balance: balancePercent(
      totals.sensitive,
      totals.seeking,
      totals.scored,
      threshold,
      totals.neutral
    ),
    // Share of answered items that flagged a sensory response either way.
    intensity: totals.scored ? Math.round((signals / totals.scored) * 100) : 0,
    meta: profileLabels[profile],
  };
}
