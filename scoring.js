function getAdultSettingReport(lifeContext, lean, domainScores = [], language = "en") {
  if (lifeContext !== "work" && lifeContext !== "home") return null;
  const pack = ADULT_SETTING_REPORT[language] || ADULT_SETTING_REPORT.en;
  const setting = pack[lifeContext];
  if (!setting) return null;

  const profile = lean === "sensitive" || lean === "seeking" ? lean : "neutral";
  const sections = (setting.sections || []).map((section) => {
    const content = section.byProfile?.[profile] || section.byProfile?.neutral || {};
    return {
      id: section.id,
      title: section.title,
      body: content.body || "",
      items: Array.isArray(content.items) ? content.items : [],
    };
  });

  const hints = [];
  const hintPack = setting.domainBreakHints || {};
  (domainScores || []).forEach((score) => {
    if (!score || score.profile === "neutral") return;
    const domainHints = hintPack[score.id];
    if (!domainHints) return;
    const tip = domainHints[score.profile];
    if (tip) {
      hints.push({
        id: score.id,
        title: score.shortTitle || score.title || score.id,
        profile: score.profile,
        text: tip,
      });
    }
  });

  // Prefer clearer patterns first; keep the list short for readability.
  hints.sort((a, b) => {
    const scoreFor = (id) => domainScores.find((s) => s.id === id);
    const strength = (id) => {
      const s = scoreFor(id);
      if (!s) return 0;
      return Math.abs((s.sensitive || 0) - (s.seeking || 0)) + ((s.sensitive || 0) + (s.seeking || 0));
    };
    return strength(b.id) - strength(a.id);
  });

  return {
    lifeContext,
    profile,
    kicker: setting.kicker,
    title: setting.title,
    intro: setting.intro,
    sections,
    domainHints: hints.slice(0, 4),
  };
}

function getWorkReportGuidance(scores, language = "en") {
  const pack = WORK_REPORT_GUIDANCE[language] || WORK_REPORT_GUIDANCE.en;
  const challenges = [];
  const recommendations = [];

  scores.forEach((score) => {
    const domain = pack[score.id];
    if (!domain) return;
    const entry = domain[score.profile] || domain.neutral;
    if (!entry) return;
    const threshold = getThresholdMeta(score.profile, language);
    challenges.push({
      id: score.id,
      title: score.shortTitle || score.title,
      profile: score.profile,
      thresholdLabel: threshold.label,
      thresholdFull: threshold.full,
      text: entry.challenge,
    });
    recommendations.push({
      id: score.id,
      title: score.shortTitle || score.title,
      profile: score.profile,
      thresholdLabel: threshold.label,
      thresholdFull: threshold.full,
      items: entry.recommendations || [],
    });
  });

  const hasSensitive = scores.some((s) => s.profile === "sensitive");
  const hasSeeking = scores.some((s) => s.profile === "seeking");
  let generalKey = "neutral";
  if (hasSensitive && !hasSeeking) generalKey = "sensitive";
  else if (hasSeeking && !hasSensitive) generalKey = "seeking";
  else if (hasSensitive && hasSeeking) {
    const sensitiveCount = scores.filter((s) => s.profile === "sensitive").length;
    const seekingCount = scores.filter((s) => s.profile === "seeking").length;
    generalKey = seekingCount > sensitiveCount ? "seeking" : "sensitive";
  }

  const general = pack.general?.[generalKey] || pack.general?.neutral || [];

  return { challenges, recommendations, general };
}

/**
 * Prefer context-specific implication/recommendation when a life setting is chosen;
 * otherwise use concise domain-level threshold readings.
 */
function getThresholdReading(domainId, profile, { language = "en", respondent = "adult", lifeContext = null } = {}) {
  const insight = lifeContext ? getContextInsight(domainId, profile, lifeContext, language) : null;
  if (insight?.looksLike && insight?.helps) {
    return {
      implication: insight.looksLike,
      recommendation: insight.helps,
      source: "context",
    };
  }

  const pack = THRESHOLD_READINGS[language] || THRESHOLD_READINGS.en;
  const perspective = respondent === "parent" ? pack.parent : pack.self;
  const domain = perspective?.[domainId];
  const reading = domain?.[profile] || domain?.neutral;
  if (!reading) {
    const labels = getProfileLabels(language, respondent);
    const meta = labels[profile] || labels.neutral;
    return {
      implication: meta.mayNotice,
      recommendation: meta.support,
      source: "profile",
    };
  }
  return { ...reading, source: "threshold" };
}

function getSensoryDietPlan(domainId, profile, language = "en", lifeContext = null) {
  const pack = SENSORY_DIET_IDEAS[language] || SENSORY_DIET_IDEAS.en;
  const domainIdeas = pack[domainId];
  if (!domainIdeas) return { contextual: [], general: [] };
  const general = domainIdeas[profile] || domainIdeas.neutral || [];
  if (!lifeContext) return { contextual: [], general };

  const contextPack = SENSORY_DIET_CONTEXT[language] || SENSORY_DIET_CONTEXT.en;
  const contexts = getCombinedLifeContexts(lifeContext);
  const contextual = [];
  for (const context of contexts) {
    const ideas =
      contextPack[context]?.[domainId]?.[profile] ||
      contextPack[context]?.[domainId]?.neutral ||
      [];
    for (const idea of ideas) {
      if (!contextual.includes(idea)) contextual.push(idea);
    }
  }

  if (!contextual.length) return { contextual: [], general };
  return { contextual, general: general.slice(0, 3) };
}

/** Rank a domain for teen cheat-sheet ordering: stronger / clearer patterns first. */
function domainRoadmapStrength(score) {
  const signals = (score.sensitive || 0) + (score.seeking || 0);
  const imbalance = Math.abs((score.sensitive || 0) - (score.seeking || 0));
  const profileBoost = score.profile === "neutral" ? 0 : 4;
  return signals * 2 + imbalance + profileBoost + (score.scored || 0) * 0.1;
}

