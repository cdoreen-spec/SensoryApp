function getContextFraming(lifeContext, language = "en") {
  const entry = getContextPack(lifeContext, language);
  if (!entry) return null;
  return {
    inSetting: entry.inSetting,
    atSetting: entry.atSetting,
    settingName: entry.settingName,
    choiceName: entry.choiceName,
  };
}

function getContextOverview(lifeContext, lean, language = "en") {
  const entry = getContextPack(lifeContext, language);
  if (!entry) return "";
  return entry.overall[lean] || entry.overall.neutral || "";
}

function getContextInsight(domainId, profile, lifeContext, language = "en") {
  if (lifeContext === "homeSchool") {
    const school = getContextInsight(domainId, profile, "school", language);
    const home = getContextInsight(domainId, profile, "home", language);
    if (!school && !home) return null;
    const isAf = language === "af";
    const parts = (schoolPart, homePart) =>
      [schoolPart && (isAf ? `By die skool: ${schoolPart}` : `At school: ${schoolPart}`), homePart && (isAf ? `By die huis: ${homePart}` : `At home: ${homePart}`)]
        .filter(Boolean)
        .join(" ");
    return {
      inSetting: isAf ? "By die huis en by die skool" : "At home and at school",
      atSetting: isAf ? "by die huis en by die skool" : "at home and at school",
      looksLike: parts(school?.looksLike, home?.looksLike),
      helps: parts(school?.helps, home?.helps),
    };
  }
  const entry = getContextPack(lifeContext, language);
  if (!entry) return null;
  const domain = entry.domains[domainId];
  if (!domain) return null;
  const insight = domain[profile] || domain.neutral;
  if (!insight) return null;
  return {
    inSetting: entry.inSetting,
    atSetting: entry.atSetting,
    looksLike: insight.looksLike,
    helps: insight.helps,
  };
}

function getProfileLabels(language = "en", respondent = "adult") {
  const copy = PROFILE_COPY[language] || PROFILE_COPY.en;
  const perspective = respondent === "parent" ? copy.parent : copy.self;
  const thresholds = THRESHOLD_META[language] || THRESHOLD_META.en;
  return Object.fromEntries(
    Object.keys(PROFILE_COLORS).map((profile) => {
      const entry = perspective[profile];
      const threshold = thresholds[profile] || thresholds.neutral;
      return [
        profile,
        {
          label: copy.labels[profile][0],
          short: copy.labels[profile][1],
          thresholdLabel: threshold.label,
          thresholdFull: threshold.full,
          thresholdKey: threshold.key,
          description: entry.description,
          mayNotice: entry.mayNotice,
          support: entry.support,
          color: PROFILE_COLORS[profile],
        },
      ];
    })
  );
}

function getThresholdMeta(profile, language = "en") {
  const pack = THRESHOLD_META[language] || THRESHOLD_META.en;
  return pack[profile] || pack.neutral;
}

